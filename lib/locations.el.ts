/** The English record plus its Greek content, looked up by Greek slug. */
export function getLocationByGreekSlug(
    elSlug: string
): { location: Location; el: LocationEl } | undefined {
    const entry = Object.entries(locationsEl).find(([, v]) => v.slug === elSlug);
    if (!entry) return undefined;
    const location = locations.find((l) => l.slug === entry[0]);
    if (!location) return undefined;
    return { location, el: entry[1] };
}

/** Greek slug for an English slug — used to build hreflang pairs. */
export function greekLocationSlugFor(enSlug: string): string | undefined {
    return locationsEl[enSlug]?.slug;
}

export const locationsElOrdered = locations
    .map((location) => ({ location, el: locationsEl[location.slug] }))
    .filter((x): x is { location: Location; el: LocationEl } => Boolean(x.el));
