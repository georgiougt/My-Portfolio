/** The English record plus its Greek content, looked up by Greek slug. */
export function getServiceByGreekSlug(
    elSlug: string
): { service: Service; el: ServiceEl } | undefined {
    const entry = Object.entries(servicesEl).find(([, v]) => v.slug === elSlug);
    if (!entry) return undefined;
    const service = services.find((s) => s.slug === entry[0]);
    if (!service) return undefined;
    return { service, el: entry[1] };
}

/** Greek slug for an English slug — used to build hreflang pairs. */
export function greekSlugFor(enSlug: string): string | undefined {
    return servicesEl[enSlug]?.slug;
}

/** Services in the same order as the English list, paired with Greek content. */
export const servicesElOrdered = services
    .map((service) => ({ service, el: servicesEl[service.slug] }))
    .filter((x): x is { service: Service; el: ServiceEl } => Boolean(x.el));
